/**
 * Suggests an Arabic name corresponding to a given Bengali name.
 * Splits multi-part names and translates matching components.
 */
export function suggestArabicName(bengaliName: string): string {
  if (!bengaliName || typeof bengaliName !== "string") return "";

  const trimmed = bengaliName.trim();
  
  // Exact match first
  if (NAME_DICTIONARY[trimmed]) {
    return NAME_DICTIONARY[trimmed];
  }

  // Token-by-token translation
  const tokens = trimmed.split(/\s+/);
  const arabicTokens: string[] = [];

  for (let i = 0; i < tokens.length; i++) {
    // Check two-word phrases first (e.g. "আব্দুর রহমান", "আবু বকর", "সাইফুল ইসলাম")
    if (i + 1 < tokens.length) {
      const phrase = `${tokens[i]} ${tokens[i + 1]}`;
      if (NAME_DICTIONARY[phrase]) {
        arabicTokens.push(NAME_DICTIONARY[phrase]);
        i++; // skip next token
        continue;
      }
    }

    const singleToken = tokens[i];
    if (NAME_DICTIONARY[singleToken]) {
      arabicTokens.push(NAME_DICTIONARY[singleToken]);
    } else {
      // Leave untranslated token as empty or phonetic fallback
      // In Islamic Madrasa ERP, we return whatever matches or preserve partial
      arabicTokens.push(singleToken);
    }
  }

  return arabicTokens.join(" ");
}
